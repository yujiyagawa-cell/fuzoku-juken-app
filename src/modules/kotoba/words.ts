/** 今の数え方で、その音・文字数に合う解答例 */
export function examplesFor(kana: string, length: 2 | 3, rules: MoraRules, max = 3): string[] {
  const w = WORDS[kana];
  if (!w) return [];
  const all = [...w[2], ...w[3]];
  return all.filter((x) => countMora(x, rules) === length && headMatches(x, kana, rules, false)).slice(0, max);
}

/** 出題できる音（濁音・半濁音を出すかは設定） */
export function kanaPool(includeDakuon: boolean): readonly string[] {
  return includeDakuon ? ALL_KANA : SEION;
}

